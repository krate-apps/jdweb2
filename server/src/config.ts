import { config as loadEnv } from 'dotenv'
import { createHash, randomBytes } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, writeFileSync, chmodSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

export const projectRoot = resolve(fileURLToPath(new URL('../..', import.meta.url)))

function readPackageVersion(): string {
  try {
    const pkg = JSON.parse(readFileSync(resolve(projectRoot, 'package.json'), 'utf8')) as { version?: string }
    return pkg.version?.trim() || '0.0.0'
  } catch {
    return '0.0.0'
  }
}

const rootEnvPath = resolve(projectRoot, '.env')
const secretsEnvPath = resolve(projectRoot, 'data/secrets.env')

loadEnv({ path: rootEnvPath })
if (existsSync(secretsEnvPath)) {
  loadEnv({ path: secretsEnvPath, override: false })
}

function env(name: string, fallback = ''): string {
  return process.env[name]?.trim() ?? fallback
}

function envInt(name: string, fallback: number): number {
  const raw = process.env[name]
  if (raw === undefined || raw === '') return fallback
  const n = Number(raw)
  return Number.isFinite(n) ? n : fallback
}

/** Normalize a public path prefix: empty or `/jdweb` (no trailing slash). */
export function normalizeBasePath(raw: string): string {
  let p = raw.trim()
  if (!p || p === '/') return ''
  if (!p.startsWith('/')) p = `/${p}`
  return p.replace(/\/+$/, '')
}

function parseDataKey(raw: string, name: string): Buffer {
  if (!/^[0-9a-fA-F]{64}$/.test(raw)) {
    throw new Error(`${name} must be 64 hex characters (32 bytes)`)
  }
  return Buffer.from(raw, 'hex')
}

/**
 * If session secret / data key are missing, write data/secrets.env (mode 600)
 * and load it. Avoids openssl copy-paste on first install.
 */
export function bootstrapSecretsFile(): { created: boolean; path: string } {
  const hasSession = Boolean(env('JDWEB2_SESSION_SECRET') && env('JDWEB2_SESSION_SECRET') !== 'dev-only-change-me')
  const hasDataKey = Boolean(env('JDWEB2_DATA_KEY'))
  if (hasSession && hasDataKey) return { created: false, path: secretsEnvPath }

  mkdirSync(dirname(secretsEnvPath), { recursive: true })
  const session = hasSession ? env('JDWEB2_SESSION_SECRET') : randomBytes(32).toString('hex')
  const dataKey = hasDataKey ? env('JDWEB2_DATA_KEY') : randomBytes(32).toString('hex')
  const body = [
    '# Auto-generated by jdweb on first run. Keep this file private (mode 600).',
    `JDWEB2_SESSION_SECRET=${session}`,
    `JDWEB2_DATA_KEY=${dataKey}`,
    '',
  ].join('\n')
  // Merge: only write keys that were missing into the file (preserve existing file content if any)
  let existing = ''
  if (existsSync(secretsEnvPath)) {
    existing = '' // rewrite only missing via env already loaded; recreate full file with both
  }
  void existing
  writeFileSync(secretsEnvPath, body, { encoding: 'utf8', mode: 0o600 })
  try {
    chmodSync(secretsEnvPath, 0o600)
  } catch {
    /* Windows may ignore */
  }
  loadEnv({ path: secretsEnvPath, override: true })
  return { created: true, path: secretsEnvPath }
}

bootstrapSecretsFile()

const DEFAULT_SESSION = 'dev-only-change-me'

function resolveDataKey(): { key: Buffer; derived: boolean } {
  const raw = env('JDWEB2_DATA_KEY')
  if (raw) return { key: parseDataKey(raw, 'JDWEB2_DATA_KEY'), derived: false }
  const secret = env('JDWEB2_SESSION_SECRET', DEFAULT_SESSION)
  console.warn(
    'JDWEB2_DATA_KEY is unset; deriving a development key from JDWEB2_SESSION_SECRET. Set JDWEB2_DATA_KEY in production.',
  )
  return {
    key: createHash('sha256').update(`jdweb-data-key:${secret}`).digest(),
    derived: true,
  }
}

function resolvePreviousDataKey(): Buffer | null {
  const raw = env('JDWEB2_DATA_KEY_PREVIOUS')
  if (!raw) return null
  return parseDataKey(raw, 'JDWEB2_DATA_KEY_PREVIOUS')
}

const dataKeyResolved = resolveDataKey()

export const config = {
  version: readPackageVersion(),
  host: env('JDWEB2_HOST', '127.0.0.1'),
  port: envInt('JDWEB2_PORT', 8787),
  basePath: normalizeBasePath(env('JDWEB2_BASE_PATH', '')),
  /** Used only to seed the first admin when the users table is empty. */
  seedUser: env('JDWEB2_USER', ''),
  seedPassword: env('JDWEB2_PASSWORD', ''),
  sessionSecret: env('JDWEB2_SESSION_SECRET', DEFAULT_SESSION),
  sessionSecretIsDefault: env('JDWEB2_SESSION_SECRET', DEFAULT_SESSION) === DEFAULT_SESSION,
  dbPath: resolve(projectRoot, env('JDWEB2_DB_PATH', './data/jdweb.sqlite')),
  dataKey: dataKeyResolved.key,
  dataKeyDerived: dataKeyResolved.derived,
  /** When set, hoster secrets are re-encrypted from this key to dataKey at boot. */
  dataKeyPrevious: resolvePreviousDataKey(),
  /** CSV of webhook URLs seeded when the webhooks table is empty. */
  webhookUrls: env('JDWEB2_WEBHOOK_URLS', '')
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean),
  webDist: resolve(projectRoot, 'web/dist'),
  secretsEnvPath,
  /** When true, refuse weak secrets (set JDWEB2_STRICT_SECRETS=1 or NODE_ENV=production). */
  strictSecrets:
    env('JDWEB2_STRICT_SECRETS', '') === '1' ||
    env('NODE_ENV', '') === 'production',
}

export function assertProductionSecrets(): void {
  if (!config.strictSecrets) return
  if (config.sessionSecretIsDefault) {
    throw new Error('JDWEB2_SESSION_SECRET must be set in production (not the development default)')
  }
  if (config.dataKeyDerived) {
    throw new Error('JDWEB2_DATA_KEY must be set in production (64 hex chars)')
  }
}
